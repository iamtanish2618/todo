import {
  copyFileSync,
  mkdirSync,
  readFileSync,
  readdirSync,
  writeFileSync,
} from "node:fs";

// Vinext's stylesheet bundler retains relative package font URLs. Publish the
// WOFF2 files explicitly and use stable public URLs in dev and production.
const dist = new URL("../node_modules/katex/dist/", import.meta.url);
const fonts = new URL("../public/fonts/katex/", import.meta.url);
mkdirSync(fonts, { recursive: true });
for (const name of readdirSync(new URL("fonts/", dist))) {
  if (name.endsWith(".woff2"))
    copyFileSync(new URL(`fonts/${name}`, dist), new URL(name, fonts));
}
copyFileSync(
  new URL("../node_modules/katex/LICENSE", import.meta.url),
  new URL("LICENSE.txt", fonts),
);
const css = readFileSync(new URL("katex.min.css", dist), "utf8").replace(
  /src:url\(fonts\/([^)]+\.woff2)\)[^}]+/g,
  'src:url("/fonts/katex/$1") format("woff2")',
);
writeFileSync(
  new URL("../vendor/katex.css", import.meta.url),
  `/* Generated by scripts/prepare-math-assets.mjs; KaTeX MIT license: /fonts/katex/LICENSE.txt */\n${css}\n`,
);
